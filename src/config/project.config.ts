export function getCurrentEnvironment():
  | "vercel"
  | "github"
  | "localhost"
  | "unknown" {
  const hostname = window.location.hostname;

  if (hostname === "localhost" || hostname === "127.0.0.1") {
    return "localhost";
  }
  if (hostname.includes("vercel.app")) {
    return "vercel";
  }
  if (hostname.includes("github.io")) {
    return "github";
  }
  return "unknown";
}

export function getBaseUrl(): string {
  const env = getCurrentEnvironment();

  switch (env) {
    case "localhost":
      return DEPLOY_URLS.localUrl;
    case "vercel":
      return DEPLOY_URLS.vercelUrl || window.location.origin;
    case "github":
      return DEPLOY_URLS.githubPagesUrl;
    default:
      return window.location.origin;
  }
}

export function getPageUrl(page: string): string {
  const base = getBaseUrl();
  return `${base}/${page}`;
}

export function getOAuthRedirectUrl(page: string = ""): string {
  return page ? getPageUrl(page) : `${getBaseUrl()}/`;
}

export function getAllowedOrigins(): string[] {
  return [
    DEPLOY_URLS.localUrl,
    DEPLOY_URLS.vercelUrl,
    DEPLOY_URLS.githubPagesUrl,
  ].filter(Boolean);
}

export function getAllowedRedirectUris(): string[] {
  const pages = ["main.html", "index.html"];
  const origins = getAllowedOrigins();

  const uris: string[] = [];

  for (const origin of origins) {
    for (const page of pages) {
      uris.push(`${origin}/${page}`);
    }
  }

  uris.push(SUPABASE_CONFIG.authCallbackUrl);

  return uris;
}

