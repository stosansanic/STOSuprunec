✅ РОЗПІЗНАВАННЯ ПОЛІВ — ТОЧНІ ПРАВИЛА:

📌 P.1 = ОБ''ЄМ ДВИГУНА (см³)
- Це завжди число від 600 до 9000
- На новому: поруч з написом "Об''єм двигуна / Capacity"
- На старому: "Об''єм дв. X куб.см" або "Об''єм двигуна X"
- На талоні: "Об''єм двигуна (см³) X"
- УВАГА: якщо бачиш число 1997, 2902, 4461, 1984, 2300, 1451 — це майже завжди P.1!
- Вводити в модалку → поле "Об''єм" (тільки число, без "куб.см")

📌 P.2 = ПОТУЖНІСТЬ (кВт)
- Це число від 30 до 600
- На новому: поруч з "Максимальна потужність / Max power"
- Буква "S" у полі P.2 = НЕ потужність, це тип палива — перевір P.3

📌 P.3 = ТИП ПАЛИВА
- Б / БЕНЗИН / S / petrol → Бензин
- Д / ДИЗЕЛЬ / D / diesel → Дизель
- Г / ГАЗ / LPG / CNG → Газ
- Е / ЕЛЕКТРО / electric → Електро
- Г+Б / ГБО → Газ
- Якщо в особливих відмітках є "ГБО", "ГАЗ", "ЗНГ" → Пальне = Газ

📌 E = VIN-КОД / НОМЕР КУЗОВА / ШАСІ / РАМИ

ФОРМАТ СПРАВЖНЬОГО VIN:
- Рівно 17 символів
- Тільки латиниця A-H, J-N, P-Z та цифри 0-9
- ЗАБОРОНЕНІ символи у VIN: I, O, Q
- WMI приклади: JTM=Toyota, KMH=Hyundai, SJN=Nissan, XTA=ВАЗ

КИРИЛИЦЯ У VIN — конвертуй автоматично:
А→A В→B С→C Е→E І→I К→K М→M Н→H О→O Р→P Т→T Х→X

НЕСТАНДАРТНІ ВИПАДКИ:
- 17 символів → це VIN → поле "VIN-код"
- Менше 17 → номер кузова → поле "Додатково" як "Кузов №: ..."
- Старі ВАЗ/ГАЗ → 8-12 символів = номер кузова, НЕ VIN

📌 КОД ДВЗ = НОМЕР ДВИГУНА
- На СТАРИХ: поле "Двигун №" → вводити в "Код ДВЗ"
- На НОВИХ пластикових — номера двигуна НЕМАЄ
- Приклад: ВАЗ 2107 → Двигун № 21037855967 → Код ДВЗ = 21037855967

