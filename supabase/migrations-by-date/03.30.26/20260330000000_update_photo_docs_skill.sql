═══ КРОК 2: КРИТИЧНІ ПРАВИЛА ═══

⛔ ЗАБОРОНЕНО:
- вигадувати або припускати значення
- пропускати P.1 — шукай ЗАВЖДИ навіть без підпису "куб.см"
