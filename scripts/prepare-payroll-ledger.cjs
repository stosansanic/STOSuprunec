// Local packaging only; never connects to or changes a database.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const prerequisite = '20261020055020_payroll_paid_price_correction.sql';
const migrations = [
  '20261020061759_traffic_payroll_payments.sql',
  '20261020061804_payroll_payment_ledger.sql',
];
const startMarker = '-- BEGIN PAYROLL PAYMENT LEDGER 2026-10-20';
const endMarker = '-- END PAYROLL PAYMENT LEDGER 2026-10-20';
const normalize = value => value.replace(/\r\n/g, '\n');
const read = name => normalize(fs.readFileSync(path.join(root, 'supabase/migrations', name), 'utf8'));
const body = source => source
  .replace(/^begin;\s*$/gm, '')
  .replace(/^commit;\s*$/gm, '')
  .replace(/^notify\s+pgrst\s*,\s*'reload schema';\s*$/gm, '').trim();
const sources = migrations.map(name => ({ name, source: read(name) }));
for (const { name, source } of sources) {
  if (!/create or replace function public\./i.test(source)) throw new Error(`Incomplete migration: ${name}`);
}
const block = startMarker + '\n' + sources.map(({ name, source }) =>
  '-- SOURCE: ' + name + '\n' + body(source)).join('\n\n') + '\n' + endMarker;
const repair = path.join(root, 'supabase/setup/traffic-optimization/payroll-payment-ledger-repair.sql');
fs.writeFileSync(repair,
  '-- Зарплата: зміна нарахування зі збереженням виплат і розрахунком різниці.\n' +
  '-- Виконайте весь файл у Supabase SQL Editor після попереднього пакета №8.\n' +
  '-- Generated by scripts/prepare-payroll-ledger.cjs. No database connection.\n' +
  'begin;\n\n-- SOURCE: ' + prerequisite + '\n' + body(read(prerequisite)) +
  '\n\n' + block + "\n\nnotify pgrst, 'reload schema';\ncommit;\n", 'utf8');
const dated = path.join(root, 'supabase/migrations-by-date/10.20.26');
fs.mkdirSync(dated, { recursive: true });
for (const { name, source } of sources) fs.writeFileSync(path.join(dated, name), source, 'utf8');

const argument = process.argv.indexOf('--template');
if (argument >= 0) {
  const target = process.argv[argument + 1];
  if (!target || !path.isAbsolute(target)) throw new Error('Expected an absolute template path.');
  const original = fs.readFileSync(target, 'utf8');
  const newline = original.includes('\r\n') ? '\r\n' : '\n';
  let template = normalize(original);
  const start = template.indexOf(startMarker), end = template.indexOf(endMarker);
  if ((start < 0) !== (end < 0) || (start >= 0 && end <= start) ||
      template.split(startMarker).length > 2 || template.split(endMarker).length > 2) {
    throw new Error('Malformed existing ledger block.');
  }
  if (!template.includes('-- END PAID WORK PRICE CORRECTION 2026-10-20') ||
      !template.includes('create or replace function public.commit_act_payroll(')) {
    throw new Error('Template requires the payroll recovery and paid-price migrations first.');
  }
  if (start >= 0) {
    template = template.slice(0, start) + block + template.slice(end + endMarker.length);
  } else {
    const tail = /notify pgrst,\s*'reload schema';\ncommit;\s*$/m.exec(template);
    if (!tail) throw new Error('Expected a final notification and commit in the consolidated template.');
    template = template.slice(0, tail.index) + block + '\n\n' + template.slice(tail.index);
  }
  const note = '-- Пакет від 20.10.2026: корекція нарахувань, збереження виплат, доплата та переплата.\n';
  template = template.replace(/^-- Пакет від [^\n]+\n/, () => note);
  template = template.replace(/^-- Повний пакет оптимізації:[^\n]+/m,
    '-- Повний пакет оптимізації: функції читання і запису, бухгалтерія та історія виплат.');
  fs.writeFileSync(target, template.replace(/\n/g, newline), 'utf8');
  const saved = normalize(fs.readFileSync(target, 'utf8'));
  if (!saved.includes(block) || saved.split(startMarker).length !== 2) {
    throw new Error('Written template does not match the source migrations.');
  }
  console.log('Updated and verified consolidated template.');
}
console.log('Prepared payroll-payment-ledger-repair.sql and dated migration copies.');
