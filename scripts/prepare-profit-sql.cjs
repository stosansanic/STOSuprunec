// Assemble the existing profit read functions and their dependencies for SQL Editor.
// This script only writes a local file; it never connects to Supabase.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const functions = [
  ['20261005100000_traffic_service_book.sql', 'sto_read_object_v1', 'jsonb'],
  ['20261011080000_traffic_payroll_json.sql', 'payroll_json_object', 'jsonb'],
  ['20261013120709_traffic_profit_date_compatibility.sql', 'traffic_profit_acts', 'text,text,text,integer'],
  ['20261010010000_traffic_receipter_salaries.sql', 'traffic_receipter_salaries', 'bigint[]'],
  ['20261012122102_accounting_traffic_optimization.sql', 'traffic_profit_labels', 'text,bigint[]'],
];
const parts = functions.map(([file, name, signature]) => {
  const source = fs.readFileSync(path.join(root, 'supabase/migrations', file), 'utf8');
  const marker = `create or replace function public.${name}(`;
  const start = source.indexOf(marker);
  if (start < 0 || source.indexOf(marker, start + marker.length) >= 0) {
    throw new Error(`Expected one definition of ${name} in ${file}`);
  }
  const body = source.indexOf('$$', start);
  const end = body < 0 ? -1 : source.indexOf('$$;', body + 2);
  if (end < 0) throw new Error(`Missing function body for ${name}`);
  const definition = source.slice(start, end + 3).replace(/\r\n/g, '\n');
  if (!definition.includes('security invoker')) throw new Error(`Expected SECURITY INVOKER: ${name}`);
  return `-- SOURCE: ${file} (${name} only)\n${definition}\n` +
    `revoke all on function public.${name}(${signature}) from public;\n` +
    `grant execute on function public.${name}(${signature}) to anon, authenticated;`;
});
const destination = path.join(root, 'supabase/setup/traffic-optimization/profit-repair.sql');
fs.mkdirSync(path.dirname(destination), {recursive: true});
fs.writeFileSync(destination,
  '-- Profit RPC repair. Run the entire file in Supabase SQL Editor, NOT Edge Functions.\n' +
  '-- Generated by scripts/prepare-profit-sql.cjs from existing migrations.\n' +
  '-- Existing acts, slyusars, clients and cars tables are required.\n' +
  '-- No tables, financial records or RLS policies are created, changed or deleted.\n' +
  '-- Functions run with caller permissions and return the existing compact report format.\n' +
  'begin;\n\n' + parts.join('\n\n') + "\n\nnotify pgrst, 'reload schema';\ncommit;\n");
console.log(`Prepared profit-repair.sql: ${functions.length} existing functions.`);
