// Local deterministic SQL packaging. Never connects to or writes a database.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const migrationName = '20261106071013_payroll_work_edit_preserve_payments.sql';
const normalize = value => value.replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
const sha = value => crypto.createHash('sha256').update(value).digest('hex');
const migration = normalize(fs.readFileSync(path.join(root, 'supabase/migrations', migrationName), 'utf8'));
for (const name of ['payroll_paid_work_adjustment_preserved', 'payroll_paid_header_adjustment_preserved', 'assert_payroll_paid_preserved']) {
  if (!migration.includes(`create or replace function public.${name}(`)) throw Error(`Incomplete migration: ${name}`);
}
const body = migration.replace(/^begin;\s*$/mi, '').replace(/^commit;\s*$/mi, '')
  .replace(/^notify\s+pgrst\s*,\s*'reload schema';\s*$/gmi, '').trim();
const start = '-- BEGIN PAID WORK EDITS 2026-11-06';
const end = '-- END PAID WORK EDITS 2026-11-06';
const block = `${start}\n${body}\n${end}`;
const standalone = `-- SQL Editor: виконати весь файл. НЕ Edge Functions.
-- Для чинної бази з пакетом зарплати та історії виплат від 20.10.2026.
-- Спочатку цей SQL, потім оновлення сайту. Для нових проєктів включити у файл 8.
-- Дозволяє перейменувати, прибрати та повернути оплачену роботу без втрати виплат.
-- Видалена робота має нульове нарахування, але попередня виплата залишається в історії.
-- Інсталяція змінює лише перевірки: не перераховує акти, не виплачує та не повертає кошти.
-- Generated by scripts/prepare-payroll-work-edit.cjs. No database connection.
begin;
${block}
notify pgrst,'reload schema';
commit;
`;
const repair = path.join(root, 'supabase/setup/traffic-optimization/payroll-work-edit-repair.sql');
fs.mkdirSync(path.dirname(repair), { recursive: true });
fs.writeFileSync(repair, standalone, 'utf8');

// An optional canonical input is read only. The prepared file remains in this workspace.
const canonical = process.argv[2];
if (canonical) {
  if (!path.isAbsolute(canonical)) throw Error('Pass the absolute path of the current file 8');
  const original = fs.readFileSync(canonical);
  let base = normalize(original.toString('utf8'));
  for (const name of ['payroll_accrual_ledger_preserved', 'write_payroll_fragments', 'commit_act_payroll']) {
    if (!base.includes(`function public.${name}(`)) throw Error(`File 8 lacks ${name}; use the latest full template`);
  }
  const previous = base.indexOf(start);
  if (previous >= 0) {
    const finish = base.indexOf(end, previous);
    if (finish < 0 || base.indexOf(start, previous + start.length) >= 0 || base.indexOf(end, finish + end.length) >= 0) {
      throw Error('Broken or duplicated paid-work-edit block');
    }
    base = base.slice(0, previous) + base.slice(finish + end.length);
  } else if (base.includes(end)) throw Error('Unmatched paid-work-edit end marker');
  const commit = /commit;\s*$/i.exec(base);
  if (!commit) throw Error('File 8 must end with COMMIT');
  const combined = base.slice(0, commit.index).trimEnd() + `\n\n${block}\n\nnotify pgrst,'reload schema';\ncommit;\n`;
  const prepared = path.join(root, 'errorSTO/payroll-work-edit-prepared');
  fs.mkdirSync(prepared, { recursive: true });
  const target = path.join(prepared, path.basename(canonical));
  fs.writeFileSync(target, combined, 'utf8');
  fs.writeFileSync(path.join(prepared, 'manifest.json'), JSON.stringify({
    canonicalSource: canonical, canonicalSourceSha256: sha(original), file8Sha256: sha(combined),
    migration: migrationName, migrationSha256: sha(migration), sqlSha256: sha(standalone),
  }, null, 2) + '\n');
  if (normalize(fs.readFileSync(target, 'utf8')).split(start).length !== 2) throw Error('Prepared block verification failed');
  console.log('Prepared workspace copy of file 8; canonical input was not modified.');
}
console.log('Prepared payroll-work-edit-repair.sql. No deployment or database writes.');
