// Packages local SQL only; never connects to or writes a database.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const migrations = [
  '20261021172731_accounting_shop_payment_scope.sql',
  '20261021172813_accounting_profit_payment_scope.sql',
];
const normalize = value => value.replace(/\r\n/g, '\n');
const source = name => normalize(fs.readFileSync(path.join(root, 'supabase/migrations', name), 'utf8'));
const body = sql => sql.replace(/^begin;\s*$/gmi, '').replace(/^commit;\s*$/gmi, '')
  .replace(/^notify\s+pgrst\s*,\s*'reload schema';\s*$/gmi, '').trim();
const start = '-- BEGIN ACCOUNTING LOADED ROW PAYMENTS 2026-10-21';
const end = '-- END ACCOUNTING LOADED ROW PAYMENTS 2026-10-21';
const sources = migrations.map(name => ({ name, sql: source(name) }));
const combined = sources.map(item => item.sql).join('\n');
for (const name of ['write_stock_payment_rows', 'write_shop_detail_payments', 'traffic_profit_payment_rows']) {
  if (!new RegExp(`create or replace function public\\.${name}\\(`, 'i').test(combined)) {
    throw Error(`Incomplete payment migrations: missing ${name}`);
  }
}
const block = `${start}\n${sources.map(({ name, sql }) => `-- SOURCE: ${name}\n${body(sql)}`).join('\n\n')}\n${end}`;
const prerequisites = `do $$ begin
  if to_regprocedure('public.sto_read_object_v1(jsonb)') is null or
     to_regprocedure('public.traffic_shop_report_v2(jsonb,integer,integer)') is null or
     to_regprocedure('public.traffic_stock_accounting_rows(jsonb)') is null or
     to_regprocedure('public.traffic_profit_accounting_day(text)') is null or
     to_regprocedure('public.traffic_profit_accounting_stamp(text)') is null or
     to_regprocedure('public.write_payroll_payment_batch(jsonb)') is null or
     to_regprocedure('public.traffic_payroll_payment_summary(jsonb,jsonb,text,text)') is null then
    raise exception 'Спочатку встановіть попередній пакет №8 з бухгалтерією та журналом зарплатних виплат';
  end if;
end $$;`;
const repair = '-- Розрахунки бухгалтерії: лише конкретні завантажені позиції; атомарні записи.\n' +
  '-- Виконати ВЕСЬ файл у Supabase → SQL Editor після попереднього пакета №8.\n' +
  '-- Це SQL, не Edge Function. Встановлення не проводить і не скасовує жодних виплат.\n' +
  '-- Generated by scripts/prepare-accounting-payments.cjs.\n' +
  `begin;\n\n${prerequisites}\n\n${block}\n\nnotify pgrst, 'reload schema';\ncommit;\n`;
const dated = path.join(root, 'supabase/migrations-by-date/10.21.26');
fs.mkdirSync(dated, { recursive: true });
for (const { name, sql } of sources) fs.writeFileSync(path.join(dated, name), sql);
fs.writeFileSync(path.join(root, 'supabase/setup/traffic-optimization/accounting-payments-repair.sql'), repair);

const flag = process.argv.indexOf('--template');
if (flag >= 0) {
  const target = process.argv[flag + 1];
  if (!target || !path.isAbsolute(target)) throw Error('Expected an absolute template path');
  const raw = fs.readFileSync(target, 'utf8'), newline = raw.includes('\r\n') ? '\r\n' : '\n';
  let template = normalize(raw);
  for (const required of ['public.sto_read_object_v1', 'public.traffic_stock_accounting_rows',
    'public.traffic_profit_accounting_day', 'public.traffic_payroll_payment_summary']) {
    if (!template.includes(required)) throw Error(`Incomplete base template: ${required}`);
  }
  const first = template.indexOf(start), last = template.indexOf(end);
  if ((first < 0) !== (last < 0) || (first >= 0 && last <= first) ||
      template.split(start).length > 2 || template.split(end).length > 2) throw Error('Malformed payment block');
  if (first >= 0) template = template.slice(0, first) + block + template.slice(last + end.length);
  else {
    const tail = /notify pgrst,\s*'reload schema';\ncommit;\s*$/.exec(template);
    if (!tail) throw Error('Missing final transaction boundary');
    template = template.slice(0, tail.index) + block + '\n\n' + template.slice(tail.index);
  }
  fs.writeFileSync(target, template.replace(/\n/g, newline));
  const saved = normalize(fs.readFileSync(target, 'utf8'));
  if (!saved.includes(block) || saved.split(start).length !== 2) throw Error('Template verification failed');
  console.log('Updated and verified consolidated file 8.');
}
console.log('Prepared accounting-payments-repair.sql and dated migration copies.');
