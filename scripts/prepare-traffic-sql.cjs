// Builds only the read-only traffic migrations; does not connect to any database.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const sourceDir = path.join(root, 'supabase/migrations');
const destination = path.join(root, 'supabase/setup/traffic-optimization/install.sql');
// Accounting page migrations also contain guarded payment operations. Their
// separate builder produces accounting-pages.sql; keep this read-only bundle so.
const names = fs.readdirSync(sourceDir).filter(name => /^\d+_traffic_.*\.sql$/.test(name) &&
  !/_traffic_(stock|profit)_accounting_page\.sql$/.test(name)).sort();
if (!names.length) throw new Error('No traffic migrations found');
const parts = names.map(name => '-- SOURCE: ' + name + '\n' +
  fs.readFileSync(path.join(sourceDir, name), 'utf8')
    .replace(/^begin;\s*$/gm, '').replace(/^commit;\s*$/gm, ''));
fs.mkdirSync(path.dirname(destination), { recursive: true });
fs.writeFileSync(destination,
  '-- Traffic read functions only. Run in Supabase SQL Editor, NOT Edge Functions.\n' +
  '-- Generated by scripts/prepare-traffic-sql.cjs. Existing tables and RLS are preserved.\n' +
  'begin;\n\n' + parts.join('\n\n') + "\n\nnotify pgrst, 'reload schema';\ncommit;\n");
console.log(`Prepared ${names.length} traffic migrations.`);
