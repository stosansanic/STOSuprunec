// Local SQL packaging only. Does not connect to or change a database.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const name = '20261021170138_planner_post_modal_integrity.sql';
const normalize = value => value.replace(/\r\n/g, '\n');
const sql = normalize(fs.readFileSync(path.join(root, 'supabase/migrations', name), 'utf8'));
if (!sql.includes('create or replace function public.traffic_planner_post_assign') ||
    !sql.includes('create or replace function public.traffic_planner_directory_write') ||
    !sql.includes('create or replace function public.traffic_planner_post_options')) {
  throw Error('Planner post migration is incomplete');
}
const body = sql.replace(/^begin;\s*$/gmi, '')
  .replace(/^commit;\s*$/gmi, '')
  .replace(/^notify pgrst,\s*'reload schema';\s*$/gmi, '').trim();
const start = '-- BEGIN PLANNER POST MODAL INTEGRITY 2026-10-21';
const end = '-- END PLANNER POST MODAL INTEGRITY 2026-10-21';
const block = `${start}\n-- SOURCE: ${name}\n${body}\n${end}`;
const repair = '-- Цехи, пости та призначення слюсаря: атомарне збереження й короткі підказки.\n' +
  '-- Виконати весь файл у Supabase SQL Editor, не в Edge Functions.\n' +
  '-- Для чинного проєкту з попереднім пакетом №8; чинні таблиці та RLS зберігаються.\n' +
  '-- Generated by scripts/prepare-planner-post-modal.cjs.\n' +
  `begin;\n\n${block}\n\nnotify pgrst, 'reload schema';\ncommit;\n`;
fs.writeFileSync(path.join(root, 'supabase/setup/traffic-optimization/planner-post-modal-repair.sql'), repair);
const dated = path.join(root, 'supabase/migrations-by-date/10.21.26');
fs.mkdirSync(dated, { recursive: true });
fs.writeFileSync(path.join(dated, name), sql);

const flag = process.argv.indexOf('--template');
if (flag >= 0) {
  const target = process.argv[flag + 1];
  if (!target || !path.isAbsolute(target)) throw Error('Expected absolute template path');
  const raw = fs.readFileSync(target, 'utf8');
  const newline = raw.includes('\r\n') ? '\r\n' : '\n';
  let template = normalize(raw);
  if (!template.includes('public.sto_read_object_v1')) throw Error('Missing base package №8');
  const first = template.indexOf(start), last = template.indexOf(end);
  if ((first < 0) !== (last < 0) || (first >= 0 && last <= first) ||
      template.split(start).length > 2 || template.split(end).length > 2) {
    throw Error('Malformed planner post modal block');
  }
  if (first >= 0) template = template.slice(0, first) + block + template.slice(last + end.length);
  else {
    const tail = /notify pgrst,\s*'reload schema';\ncommit;\s*$/.exec(template);
    if (!tail) throw Error('Missing final transaction boundary');
    template = template.slice(0, tail.index) + block + '\n\n' + template.slice(tail.index);
  }
  fs.writeFileSync(target, template.replace(/\n/g, newline));
  const saved = normalize(fs.readFileSync(target, 'utf8'));
  if (!saved.includes(block) || saved.split(start).length !== 2) throw Error('Template verification failed');
  console.log('Updated and verified consolidated file 8.');
}
console.log('Prepared planner-post-modal-repair.sql and dated migration copy.');
