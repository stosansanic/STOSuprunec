const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const name='20261021163459_client_car_modal_integrity.sql';
const normalize=s=>s.replace(/\r\n/g,'\n');
const sql=normalize(fs.readFileSync(path.join(root,'supabase/migrations',name),'utf8'));
const body=sql.replace(/^begin;\s*$/gm,'').replace(/^commit;\s*$/gm,'').replace(/^notify pgrst,\s*'reload schema';\s*$/gm,'').trim();
const start='-- BEGIN CLIENT CAR MODAL INTEGRITY 2026-10-21',end='-- END CLIENT CAR MODAL INTEGRITY 2026-10-21';
const block=start+'\n-- SOURCE: '+name+'\n'+body+'\n'+end;
const repair='-- Клієнти та автомобілі: додавання, редагування, приховування, відновлення за VIN.\n-- Supabase SQL Editor, не Edge Functions. Виконати весь файл після попереднього пакета №8.\n-- Чинні таблиці та RLS збережені. Клієнти, автомобілі й акти не видаляються.\n-- Generated by scripts/prepare-client-car-modal.cjs.\nbegin;\n\n'+block+"\n\nnotify pgrst, 'reload schema';\ncommit;\n";
fs.writeFileSync(path.join(root,'supabase/setup/traffic-optimization/client-car-modal-repair.sql'),repair,'utf8');
const dated=path.join(root,'supabase/migrations-by-date/10.21.26');fs.mkdirSync(dated,{recursive:true});fs.writeFileSync(path.join(dated,name),sql,'utf8');
const flag=process.argv.indexOf('--template');
if(flag>=0){
 const target=process.argv[flag+1];if(!target||!path.isAbsolute(target))throw Error('Expected absolute template path');
 const raw=fs.readFileSync(target,'utf8'),newline=raw.includes('\r\n')?'\r\n':'\n';let template=normalize(raw);
 if(!template.includes('public.sto_read_object_v1')||!template.includes('public.traffic_client_form_options'))throw Error('Missing client/car prerequisites');
 const first=template.indexOf(start),last=template.indexOf(end);
 if((first<0)!==(last<0)||(first>=0&&last<=first)||template.split(start).length>2||template.split(end).length>2)throw Error('Malformed client/car block');
 if(first>=0)template=template.slice(0,first)+block+template.slice(last+end.length);
 else{const tail=/notify pgrst,\s*'reload schema';\ncommit;\s*$/.exec(template);if(!tail)throw Error('Missing final transaction boundary');template=template.slice(0,tail.index)+block+'\n\n'+template.slice(tail.index);}
 fs.writeFileSync(target,template.replace(/\n/g,newline),'utf8');
 const saved=normalize(fs.readFileSync(target,'utf8'));if(!saved.includes(block)||saved.split(start).length!==2)throw Error('Template verification failed');
 console.log('Updated and verified consolidated file 8.');
}
