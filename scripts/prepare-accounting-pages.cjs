// Build the targeted accounting upgrade; never connects to a database.
// Optional --template <absolute path> updates the already-consolidated file 8.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const migrations = [
  '20261015154333_traffic_stock_accounting_page.sql',
  '20261015154335_traffic_profit_accounting_page.sql',
];
const beginMarker = '-- BEGIN ACCOUNTING CURSOR PAGES 2026-10-15';
const endMarker = '-- END ACCOUNTING CURSOR PAGES 2026-10-15';
const sources = migrations.map(name => {
  const source = fs.readFileSync(path.join(root, 'supabase/migrations', name), 'utf8');
  if (!/create or replace function public\.traffic_(stock|profit)_accounting_page\(/i.test(source)) {
    throw new Error(`Incomplete accounting migration: ${name}`);
  }
  return {name, source};
});
const block = beginMarker + '\n' + sources.map(({name, source}) =>
  '-- SOURCE: ' + name + '\n' + source.replace(/\r\n/g, '\n')
    .replace(/^\s*begin;\s*$/gmi, '')
    .replace(/^\s*commit;\s*$/gmi, '')
    .replace(/^\s*notify\s+pgrst\s*,\s*'reload schema';\s*$/gmi, '').trim()
).join('\n\n') + '\n' + endMarker;
const destination = path.join(root, 'supabase/setup/traffic-optimization/accounting-pages.sql');
fs.mkdirSync(path.dirname(destination), {recursive: true});
fs.writeFileSync(destination,
  '-- Бухгалтерія: серверні підсумки, порції рядків, контроль масової оплати.\n' +
  '-- Виконати весь файл у Supabase SQL Editor після чинного пакета №8.\n' +
  '-- Це SQL, не код Edge Function. Business tables and RLS policies are preserved.\n' +
  '-- Generated by scripts/prepare-accounting-pages.cjs. No database connection.\n' +
  'begin;\n\n' +
  "do $$ begin\n" +
  "  if to_regprocedure('public.sto_read_object_v1(jsonb)') is null or\n" +
  "     to_regprocedure('public.traffic_json_object(jsonb)') is null or\n" +
  "     to_regprocedure('public.traffic_shop_date(text)') is null then\n" +
  "    raise exception 'Спочатку встановіть чинний пакет №8: відсутні базові функції читання';\n" +
  "  end if;\nend $$;\n\n" +
  block + "\n\nnotify pgrst, 'reload schema';\ncommit;\n", 'utf8');
const dated = path.join(root, 'supabase/migrations-by-date/10.15.26');
fs.mkdirSync(dated, {recursive: true});
for (const {name, source} of sources) fs.writeFileSync(path.join(dated, name), source, 'utf8');

const templateArg = process.argv.indexOf('--template');
if (templateArg !== -1) {
  const template = process.argv[templateArg + 1];
  if (!template || !path.isAbsolute(template)) throw new Error('An absolute template path is required.');
  let source = fs.readFileSync(template, 'utf8').replace(/\r\n/g, '\n');
  const start = source.indexOf(beginMarker), end = source.indexOf(endMarker);
  if ((start < 0) !== (end < 0) || (start >= 0 && end < start)) throw new Error('Malformed existing accounting bundle.');
  if (start >= 0) source = source.slice(0, start) + source.slice(end + endMarker.length);
  // Replace only our own generated section. Keep the existing migration order,
  // hand-written fixes and final transaction intact.
  const commit = /\bcommit;\s*$/i.exec(source);
  if (!commit || !/^begin;\s*$/mi.test(source)) throw new Error('Expected one consolidated transaction in template.');
  if (!/traffic_stock_accounting_page\(/.test(source) && !/traffic_profit_accounting_page\(/.test(source)) {
    source = source.slice(0, commit.index) + '\n' + block + "\n\nnotify pgrst, 'reload schema';\n" + source.slice(commit.index);
  } else {
    throw new Error('Accounting definitions outside generated block; manual reconciliation required.');
  }
  const note = '-- Пакет від 15.10.2026: серверні підсумки та порції складу/прибутку включені нижче.\n';
  if (!source.includes(note.trim())) source = note + source;
  fs.writeFileSync(template, source, 'utf8');
  console.log(`Updated consolidated template: ${template}`);
}
console.log(`Prepared accounting-pages.sql and ${sources.length} dated migrations.`);
